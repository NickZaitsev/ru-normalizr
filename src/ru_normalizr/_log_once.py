"""Предупреждения с дедупликацией по токену.

Сбои `num2words` и морфологии повторяются на каждом вхождении проблемного
токена: на книжном корпусе один неудачный токен давал бы тысячи одинаковых
строк в логе. Раньше их прятали в DEBUG — и тогда пользователь не видел вообще
ничего, токен молча оставался ненормализованным. Здесь уровень WARNING, но
каждый уникальный токен предупреждает о себе один раз.
"""

from __future__ import annotations

import logging
import threading

#: Сколько токенов помнить. При переполнении набор сбрасывается целиком: LRU не
#: нужен, цель не «ни одного повтора», а «лог не растёт линейно от объёма текста»,
#: и сам набор не растёт линейно от числа уникальных сбойных токенов.
_MAX_REMEMBERED = 512

_warned: set[tuple[str, str]] = set()
_warned_lock = threading.Lock()


def warn_once(logger: logging.Logger, key: str, message: str, *args: object) -> None:
    """Записать `message` на уровне WARNING один раз на пару (логгер, `key`).

    `key` должен различать и токен, и место сбоя: один и тот же токен может не
    отрендериться по разным причинам, и вторую причину не стоит терять из-за
    того, что о первой уже сообщили.
    """
    entry = (logger.name, key)
    with _warned_lock:
        if entry in _warned:
            return
        if len(_warned) >= _MAX_REMEMBERED:
            _warned.clear()
        _warned.add(entry)
    logger.warning(message, *args)


def reset_warn_once_cache() -> None:
    """Забыть, о каких токенах уже предупреждали.

    Нужно тестам и долгоживущим сервисам, которым важно снова увидеть
    предупреждение о токене из нового документа.
    """
    with _warned_lock:
        _warned.clear()
