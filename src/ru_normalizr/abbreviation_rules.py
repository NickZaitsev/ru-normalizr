@dataclass(frozen=True, slots=True)
class RegexRule:
    pattern: str
    flags: int = re.IGNORECASE


def rx(pattern: str, flags: int = re.IGNORECASE) -> RegexRule:
    return RegexRule(pattern=pattern, flags=flags)


