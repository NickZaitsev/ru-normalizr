def test_social_media_handle_uses_marker_words_and_the_existing_latinization_contract() -> None:
    source = "Напишите пользователю @support_team и укажите номер заявки № 42."
    options = NormalizeOptions.tts(latinization_backend="dictionary")
    assert normalize(source, options) == (
        "Напишите пользователю собака сапорт подчёркивание тим и укажите номер заявки "
        "номер сорок два."
    )


